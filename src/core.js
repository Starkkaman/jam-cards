/* ---------- light colour helpers ---------- */
/* Approximate rgb of a colour temperature (Tanner Helland's black-body fit), e.g. 2200 K -> [255,146,39]. */
function kelvinToRgb(k) {
  const t = Math.max(1000, Math.min(40000, Number(k) || 2700)) / 100;
  let r, g, b;
  if (t <= 66) { r = 255; g = 99.4708025861 * Math.log(t) - 161.1195681661; b = t <= 19 ? 0 : 138.5177312231 * Math.log(t - 10) - 305.0447927307; }
  else { r = 329.698727446 * Math.pow(t - 60, -0.1332047592); g = 288.1221695283 * Math.pow(t - 60, -0.0755148492); b = 255; }
  return [r, g, b].map(v => Math.round(Math.max(0, Math.min(255, v))));
}
/* WCAG relative luminance of [r,g,b] (0..1). */
function luminance(c) {
  const l = c.map(v => { v = Math.max(0, Math.min(255, Number(v) || 0)) / 255; return v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; });
  return .2126 * l[0] + .7152 * l[1] + .0722 * l[2];
}
/* Text on a flat [r,g,b] fill: the look's dark text on light colours (luminance > .18), its light text on dark ones.
   tc = textColors(node) (default: the Poster pair, ink #141210 / paper #ece2c9). */
function inkOn(c, tc = JAM_TEXT_POSTER) { return luminance(c) > .18 ? tc.darkCss : tc.lightCss; }
/* A light's actual output colour as [r,g,b], or null: kelvin -> rgb in color_temp mode, else rgb_color. */
function lightRgb(s) {
  const a = (s && s.attributes) || {};
  if (a.color_mode === "color_temp" && a.color_temp_kelvin) return kelvinToRgb(a.color_temp_kelvin);
  if (Array.isArray(a.rgb_color) && a.rgb_color.length >= 3) return a.rgb_color.slice(0, 3).map(Number);
  if (a.color_temp_kelvin) return kelvinToRgb(a.color_temp_kelvin);
  return null;
}
/* A colour's hue at full value: [r,g,b] scaled so the largest channel is 255 (WLED reports brightness-scaled rgb_color,
   e.g. [51,20,0] -> [255,100,0]). null for a missing or black colour. */
function fullRgb(c) {
  if (!Array.isArray(c) || c.length < 3) return null;
  const v = c.slice(0, 3).map(x => Math.max(0, Number(x) || 0)), m = Math.max(...v);
  return m > 0 ? v.map(x => Math.min(255, Math.round(x * 255 / m))) : null;
}
const rgbCss = c => `rgb(${c.slice(0, 3).map(v => Math.round(Number(v) || 0)).join(",")})`;

/* ---------- face shades + power corner (ROUND3 "Interaction rule", round 3) ---------- */
/* WCAG contrast ratio of two [r,g,b] colours (1..21). */
function contrastRatio(a, b) {
  const x = luminance(a), y = luminance(b);
  return (Math.max(x, y) + .05) / (Math.min(x, y) + .05);
}
/* Colour maths per look (theming plan R4). The two text colours a flat face can carry: dark = the look's --on-fg (text on
   any accent fill), light = its --ink-fg (text on ink), sorted by luminance; [r,g,b] for the maths + the token's own CSS
   value for the style. Poster: ink #141210 / paper #ece2c9 in both modes (the fallback when a node is not connected or a
   token does not resolve to rgb). */
const JAM_TEXT_POSTER = Object.freeze({dark: Object.freeze([20, 18, 16]), light: Object.freeze([236, 226, 201]), darkCss: "#141210", lightCss: "#ece2c9"});
const JAM_INK_RGB = JAM_TEXT_POSTER.dark, JAM_PAPER_RGB = JAM_TEXT_POSTER.light;
/* [r,g,b] of a hex (#rgb, #rrggbb, #rrggbbaa) or rgb()/rgba() string, else null. */
function parseRgb(v) {
  const s = String(v || "").trim(), h = /^#([\da-f]{3}|[\da-f]{6}|[\da-f]{8})$/i.exec(s);
  if (h) { const x = h[1].length === 3 ? [...h[1]].map(c => c + c).join("") : h[1].slice(0, 6); return [0, 2, 4].map(i => parseInt(x.slice(i, i + 2), 16)); }
  const m = /^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/i.exec(s);
  return m ? [+m[1], +m[2], +m[3]].map(Math.round) : null;
}
const TEXT_CACHE = new Map();
/* The look's text pair at node (one computed-style read; resolved pairs cached by their token values, so a look or mode
   switch picks up new values on the next render). */
function textColors(node) {
  let a = "", b = "";
  try { if (node && node.isConnected) { const cs = getComputedStyle(node); a = cs.getPropertyValue("--on-fg").trim(); b = cs.getPropertyValue("--ink-fg").trim(); } } catch (e) { /* Poster */ }
  if (!a || !b) return JAM_TEXT_POSTER;
  const k = a + "|" + b;
  let t = TEXT_CACHE.get(k);
  if (!t) {
    const A = parseRgb(a) || resolveRgb(node, a), B = parseRgb(b) || resolveRgb(node, b);
    if (!A || !B) return JAM_TEXT_POSTER;
    const [d, l] = luminance(A) <= luminance(B) ? [[A, a], [B, b]] : [[B, b], [A, a]];
    t = Object.freeze({dark: Object.freeze(d[0]), light: Object.freeze(l[0]), darkCss: d[1], lightCss: l[1]});
    if (TEXT_CACHE.size >= 16) TEXT_CACHE.clear();
    TEXT_CACHE.set(k, t);
  }
  return t;
}
/* Text on a flat [r,g,b] face: {fg: the dark or light text (tc), whichever contrasts more, dark: true when that is the
   dark one, plate: true when neither reaches 4.5:1 (the card then puts its text on a label plate, --plate)}. */
function textOn(c, tc = JAM_TEXT_POSTER) {
  const ink = contrastRatio(c, tc.dark), pap = contrastRatio(c, tc.light);
  return {fg: ink >= pap ? tc.darkCss : tc.lightCss, plate: Math.max(ink, pap) < 4.5, dark: ink >= pap};
}
/* A shade of a face colour [r,g,b] (flat, same hue): depth 1 = mid (power corner, strip fill), 2 = deep (strip track).
   Light faces (ink text, luminance > .18) get darker, dark faces lighter, so the shade always reads as part of the face. */
function shade(c, depth = 1) {
  const [r, g, b] = c.slice(0, 3).map(v => Math.max(0, Math.min(255, Number(v) || 0)) / 255);
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn; // d = chroma
  let h = 0, l = (mx + mn) / 2;
  if (d) {
    h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h = (h * 60 + 360) % 360;
  }
  const step = depth >= 2 ? .36 : .24;
  l = luminance(c) > .18 ? Math.max(.06, l - step) : Math.min(.9, l + step);
  // Keep the face's chroma (not its HSL saturation, which near white is huge for a tiny tint), slightly muted.
  const s = Math.min(1, d / Math.max(1e-6, 1 - Math.abs(2 * l - 1))) * .85;
  const a = s * Math.min(l, 1 - l), f = n => { const k = (n + h / 30) % 12; return Math.round(255 * (l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)))); };
  return [f(0), f(8), f(4)];
}
/* The computed [r,g,b] of a CSS colour (e.g. "var(--acc)") inside node's tree, or null when node is not connected or the
   colour does not resolve to rgb(). Used to shade a face whose colour is a theme token. */
function resolveRgb(node, css) {
  if (!node || !node.isConnected) return null;
  const p = document.createElement("span");
  p.style.color = css; p.style.display = "none"; node.append(p);
  const m = /rgba?\(([\d.]+),\s*([\d.]+),\s*([\d.]+)/.exec(getComputedStyle(p).color || "");
  p.remove();
  return m ? [+m[1], +m[2], +m[3]].map(Math.round) : null;
}
