#!/usr/bin/env node
// Writes the Home Assistant theme YAML of the Hi-Fi look from the token source (tokens/) into the jam-theme repo.
//   node tools/themes.mjs                 write ../jam-theme/themes/jamboard.yaml (themes "Hi-Fi", "Hi-Fi Day", "Hi-Fi Night";
//                                         JAM_THEME_DIR=<dir> = another themes folder, e.g. a jam-theme worktree's)
//   node tools/themes.mjs --check         exit 1 if a file is stale (tools/bundle.mjs --check runs this too)
//   node tools/themes.mjs --out <dir>     another themes folder
// Order per file: header comment, the theme name, chrome keys + theme-level --jam-* tokens, card-mod view tabs, then per
// mode the --jam-* palette (registry order) and the derived HA keys (tokens/ha.mjs); then each single-mode theme of the look
// (look.single, 1.0.1: "Hi-Fi Day" / "Hi-Fi Night"): the same top level with one mode's palette flat, no modes.
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {TOKENS, LOOKS, HA_KEYS, haValue} from "../tokens/index.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const THEME_DIR = process.env.JAM_THEME_DIR ? path.resolve(process.env.JAM_THEME_DIR) : path.join(ROOT, "..", "jam-theme", "themes");

const q = v => (String(v).includes('"') ? `'${String(v).replace(/'/g, "''")}'` : `"${v}"`);

/* Top level of a theme: chrome keys, theme-level --jam-* tokens, the card-mod view tabs (card-mod-theme = the theme name). */
function topLines(look, name, L, modes) {
  L.push(`  # ---- shape + type${modes ? " (both modes)" : ""} ----`);
  for (const [k, v] of look.chrome || []) L.push(`  ${k}: ${q(v)}`);
  for (const t of TOKENS) if (t.scope === "theme" && look.tokens && t.name in look.tokens) L.push(`  ${t.name}: ${q(look.tokens[t.name])}`);
  if (look.cardModRoot) {
    L.push('  # ---- dashboard view tabs in the app header (needs card-mod 4.x, HACS "lovelace-card-mod") ----');
    for (const c of look.cardModComment || []) L.push("  # " + c);
    L.push(`  card-mod-theme: ${q(name)}`);
    L.push("  card-mod-root: |");
    for (const line of look.cardModRoot.replace(/\n$/, "").split("\n")) L.push(line ? "    " + line : "");
  }
}
/* One mode's palette: the --jam-* tokens (registry order), then the derived HA keys (tokens/ha.mjs), at indent ind. */
function modeLines(mode, ind, L) {
  for (const t of TOKENS) if (t.scope === "mode" && t.name in mode.tokens) L.push(`${ind}${t.name}: ${q(mode.tokens[t.name])}`);
  for (const e of HA_KEYS) {
    if (typeof e === "string") L.push(ind + e);
    else L.push(`${ind}${e[0]}: ${q(haValue(e[1], mode))}`);
  }
}

/* The theme file of a look: the theme with modes (look.theme), then each single-mode theme of look.single ([name, mode]: the
   same top level + that mode's palette as flat top-level keys, no modes), all from the same token source. */
export function themeYaml(look) {
  const L = [`# GENERATED by jam-cards tools/themes.mjs from tokens/looks/${look.id}.mjs: edit the token source there, not this file.`];
  for (const c of look.comment || []) L.push("# " + c);
  L.push(`${look.theme}:`);
  topLines(look, look.theme, L, true);
  L.push("", "  modes:");
  for (const [m, mode] of Object.entries(look.modes)) {
    L.push(`    ${m}:`);
    if (mode.comment) L.push("      # " + mode.comment);
    modeLines(mode, "      ", L);
  }
  for (const [name, m] of look.single || []) {
    const mode = look.modes[m];
    if (!mode) throw new Error(`token source: ${look.id} single theme ${name}: no mode ${m}`);
    L.push("", `# ${name}: ${look.theme}'s ${m} palette alone (no modes): it stays the same whatever the device's dark setting.`);
    L.push(`${name}:`);
    topLines(look, name, L, false);
    L.push(`  # ---- ${mode.comment || m} (the only palette of this theme) ----`);
    modeLines(mode, "  ", L);
  }
  return L.join("\n") + "\n";
}

/* {absolute path: content} for every look (not the harness-only or draft ones). */
export function themeFiles(dir = THEME_DIR) {
  return Object.fromEntries(LOOKS.filter(l => !l.harness && !l.draft).map(l => [path.join(dir, l.file), themeYaml(l)]));
}
/* Stale theme files (list of paths); [] when dir does not exist and optional is set. */
export function staleThemes(dir = THEME_DIR, optional = false) {
  if (optional && !fs.existsSync(dir)) return [];
  return Object.entries(themeFiles(dir)).filter(([f, s]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== s).map(([f]) => f);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf("--out"), dir = i > 0 ? path.resolve(process.argv[i + 1]) : THEME_DIR;
  if (!fs.existsSync(dir)) { console.error("no themes folder at " + dir + " (clone jam-theme next to jam-cards, or pass --out)"); process.exit(1); }
  if (process.argv.includes("--check")) {
    const stale = staleThemes(dir);
    if (stale.length) { console.error("STALE: " + stale.join(", ") + " — run node tools/themes.mjs"); process.exit(1); }
    console.log("themes up to date");
  } else {
    const files = themeFiles(dir);
    for (const [f, s] of Object.entries(files)) fs.writeFileSync(f, s);
    console.log(`wrote ${Object.keys(files).length} theme file(s): ${Object.keys(files).map(f => path.relative(ROOT, f)).join(", ")}`);
  }
}
